// Emits typescript/src/generated: the types of each spec, the operation table and the resource
// classes of the client.
import type { Api, Ir, Model, Operation, TypeRef } from './ir.ts';
import { camel } from './ir.ts';
import { buildTree, walk, type Node } from './tree.ts';

const HEADER = (source: string) => `// Generated by generator/src/main.ts from ${source}. Do not edit; run \`bun run generate\`.\n`;
const ALIAS: Record<Api, string> = { platform: 'P', connect: 'C', live: 'L' };
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function doc(text: string | undefined, indent = ''): string {
  if (!text) return '';
  const lines = text.replace(/\*\//g, '*\\/').trim().split('\n');
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l ? ` ${l}` : ''}`).join('\n')}\n${indent} */\n`;
}

/** The TypeScript type of a TypeRef. `qualify` prefixes model names with their module alias. */
export function tsType(t: TypeRef, qualify = false): string {
  switch (t.kind) {
    case 'ref':
      return qualify ? `${ALIAS[t.api]}.${t.name}` : t.name;
    case 'string':
      return t.enum ? `${t.enum.map((e) => JSON.stringify(e)).join(' | ')} | (string & {})` : 'string';
    case 'literal':
      return JSON.stringify(t.value);
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'unknown':
      return 'unknown';
    case 'binary':
      return 'Uploadable';
    case 'array': {
      const inner = tsType(t.items, qualify);
      return /[ |&]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
    }
    case 'map':
      return `Record<string, ${tsType(t.values, qualify)}>`;
    case 'union':
      return t.of.map((u) => tsType(u, qualify)).join(' | ');
  }
}

function usesBinary(t: TypeRef): boolean {
  if (t.kind === 'binary') return true;
  if (t.kind === 'array') return usesBinary(t.items);
  if (t.kind === 'map') return usesBinary(t.values);
  if (t.kind === 'union') return t.of.some(usesBinary);
  return false;
}

export function emitTypes(models: Map<string, Model>, source: string): string {
  let out = HEADER(source);
  const all = [...models.values()];
  if (all.some((m) => (m.kind === 'object' ? m.props.some((p) => usesBinary(p.type)) : usesBinary(m.type)))) out += "import type { Uploadable } from '../../core/uploads.ts';\n";
  for (const m of all) {
    out += '\n';
    out += doc(m.description);
    if (m.kind === 'alias') {
      out += `export type ${m.name} = ${tsType(m.type)};\n`;
      continue;
    }
    out += `export interface ${m.name} {\n`;
    for (const p of m.props) {
      const key = IDENT.test(p.name) ? p.name : JSON.stringify(p.name);
      out += doc(p.deprecated ? `${p.description ?? ''}\n\n@deprecated`.trim() : p.description, '  ');
      out += `  ${key}${p.required ? '' : '?'}: ${tsType(p.type)};\n`;
    }
    if (m.additional) out += `  [key: string]: ${m.props.length ? 'unknown' : tsType(m.additional)};\n`;
    out += '}\n';
  }
  return out;
}

export function opDoc(op: Operation): string {
  const parts = [op.summary, op.description && op.description !== op.summary ? op.description : undefined].filter(Boolean) as string[];
  const facts = [`\`${op.httpMethod} ${op.path}\``];
  if (op.x.scope) facts.push(`scope \`${op.x.scope}\``);
  if (op.x.verb) facts.push(`verb \`${op.x.verb}\``);
  if (op.x.phi) facts.push('answers hold patient data');
  if (op.x.metered) facts.push(`metered as \`${op.x.metered}\``);
  if (op.idempotency === 'required') facts.push('Idempotency-Key required (the SDK makes one)');
  parts.push(facts.join(', ') + '.');
  return parts.join('\n\n');
}

export function emitOperations(ir: Ir): string {
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += "import type { OperationMeta } from '../core/operation.ts';\n\n";
  out += `/** The API version of the specs this SDK was generated from. */\nexport const API_VERSION = ${JSON.stringify(ir.version)};\n\n`;
  out += 'export const OPERATIONS = {\n';
  for (const op of ir.operations) {
    const meta = {
      api: op.api,
      operationId: op.operationId,
      method: op.httpMethod,
      path: op.path,
      body: op.body?.encoding ?? null,
      query: !!op.queryModel,
      response: op.response.kind,
      idempotency: op.idempotency,
      paginated: !!op.page,
      ...(op.query.some((q) => q.comma) ? { commaQuery: op.query.filter((q) => q.comma).map((q) => q.name) } : {}),
      ...op.x,
    };
    out += `  ${JSON.stringify(op.name)}: ${JSON.stringify(meta)},\n`;
  }
  out += '} as const satisfies Record<string, OperationMeta>;\n\n';
  out += `/** Helpers on the client that are no API operation. */\nexport const HELPERS = ${JSON.stringify(ir.helpers.map((h) => h.name))} as const;\n`;
  return out;
}

const HELPER_TS: Record<string, { sig: string; body: string; doc?: string }> = {
  'audio.transcriptions.wait': {
    sig: 'wait(id: string, options?: TranscriptionWaitOptions): Promise<P.Transcription>',
    body: 'return waitForTranscription((i, o) => this.get(i, o), id, options);',
  },
  'connect.transfers.wait': {
    sig: 'wait(transferId: string, options?: TransferWaitOptions): Promise<C.Transfer>',
    body: 'return waitForTransfer((i, o) => this.get(i, o), transferId, options);',
  },
  'connect.events.poll': {
    sig: 'poll(query: C.EventsListQuery = {}, options?: PollOptions): AsyncGenerator<Page<C.Event, C.EventList>, void, undefined>',
    body: 'return pollEvents((cursor, o) => this.list({ ...query, ...(cursor ? { cursor } : {}) }, o), query.cursor ?? undefined, options);',
  },
  'connect.capabilities.forConnection': {
    sig: 'forConnection(connectionId: string): Capabilities',
    body: 'return new Capabilities(connectionId, () => this.get(connectionId));',
  },
};

const CUSTOM_TS: Record<string, { sig: string; body: string }> = {
  'audio.stream.open': {
    sig: 'open(options: StreamOptions = {}): Promise<LiveStream>',
    body: 'return openStream(this._client, options);',
  },
};

function returnType(op: Operation): string {
  switch (op.response.kind) {
    case 'empty':
      return 'void';
    case 'binary':
      return 'Blob';
    case 'text':
      return 'string';
    case 'json':
      return op.response.type && op.response.type.kind !== 'unknown' ? tsType(op.response.type, true) : 'Record<string, unknown>';
  }
}

function method(op: Operation, name: string): string {
  const args: string[] = [];
  const pathArgs: string[] = [];
  for (const p of op.pathParams) {
    const id = camel(p.name);
    args.push(`${id}: ${tsType(p.type, true)}`);
    pathArgs.push(p.name === id ? id : `${p.name}: ${id}`);
  }
  const call: string[] = [];
  if (pathArgs.length) call.push(`path: { ${pathArgs.join(', ')} }`);
  if (op.body) {
    args.push(`body${op.body.required ? '' : '?'}: ${ALIAS[op.api]}.${op.body.model}`);
    call.push('body');
  }
  if (op.queryModel) {
    const required = op.query.some((q) => q.required);
    args.push(`query${required ? '' : '?'}: ${ALIAS[op.api]}.${op.queryModel}`);
    call.push('query');
  }
  args.push('options?: RequestOptions');
  const ref = `OPERATIONS[${JSON.stringify(op.name)}]`;
  const callArgs = `{ ${call.join(', ')} }`.replace('{  }', '{}');
  let out = doc(opDoc(op), '  ');
  if (op.page) {
    const item = tsType(op.page.item, true);
    const raw = returnType(op);
    out += `  ${name}(${args.join(', ')}): PagePromise<${item}, ${raw}> {\n`;
    out += `    return this._client.requestPage<${item}, ${raw}>(${ref}, ${callArgs}, options);\n  }\n`;
  } else {
    const rt = returnType(op);
    out += `  ${name}(${args.join(', ')}): Promise<${rt}> {\n`;
    out += `    return this._client.request<${rt}>(${ref}, ${callArgs}, options);\n  }\n`;
  }
  return out;
}

function nodeClass(node: Node, isRoot: boolean): string {
  let out = '';
  const name = isRoot ? 'MediSyncResources' : node.className;
  out += isRoot
    ? `/** The resources of the MediSync client. Use the \`MediSync\` class. */\nexport class ${name} extends MediSyncCore {\n`
    : `export class ${name} extends APIResource {\n`;
  for (const [key, child] of node.children) out += `  readonly ${key}: ${child.className};\n`;
  if (isRoot) {
    out += '\n  constructor(options: ClientOptions = {}) {\n    super(options);\n';
    for (const [key, child] of node.children) out += `    this.${key} = new ${child.className}(this);\n`;
    out += '  }\n';
  } else if (node.children.size) {
    out += '\n  constructor(client: MediSyncCore) {\n    super(client);\n';
    for (const [key, child] of node.children) out += `    this.${key} = new ${child.className}(client);\n`;
    out += '  }\n';
  }
  for (const m of node.methods) {
    out += '\n';
    if (m.helper) {
      const h = HELPER_TS[m.helper.name];
      if (!h) throw new Error(`No TypeScript helper for ${m.helper.name}`);
      out += doc(m.helper.doc, '  ');
      out += `  ${h.sig} {\n    ${h.body}\n  }\n`;
    } else if (m.op?.custom) {
      const c = CUSTOM_TS[m.op.name];
      if (!c) throw new Error(`No TypeScript code for the custom operation ${m.op.name}`);
      out += doc(opDoc(m.op), '  ');
      out += `  ${c.sig} {\n    ${c.body}\n  }\n`;
    } else if (m.op) {
      out += method(m.op, m.name);
    }
  }
  out += '}\n';
  return out;
}

export function emitResources(ir: Ir): string {
  const tree = buildTree(ir);
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += `import type * as P from './types/platform.ts';
import type * as C from './types/connect.ts';
import { MediSyncCore, type ClientOptions } from '../core/client.ts';
import { APIResource } from '../core/resource.ts';
import type { RequestOptions } from '../core/operation.ts';
import type { Page, PagePromise } from '../core/pagination.ts';
import { OPERATIONS } from './operations.ts';
import { waitForTranscription, type TranscriptionWaitOptions } from '../helpers/transcriptions.ts';
import { pollEvents, waitForTransfer, type PollOptions, type TransferWaitOptions } from '../connect/follow.ts';
import { Capabilities } from '../connect/capabilities.ts';
import { openStream, type LiveStream, type StreamOptions } from '../live/stream.ts';
`;
  const classes: string[] = [];
  walk(tree, (node) => {
    if (node !== tree) classes.push(nodeClass(node, false));
  });
  for (const c of classes) out += `\n${c}`;
  out += `\n${nodeClass(tree, true)}`;
  return out;
}

/** The dotted method names of the client, for the parity tests of every language. */
export function methodNames(ir: Ir): { operations: { api: string; operationId: string; name: string }[]; helpers: string[] } {
  return {
    operations: ir.operations.map((o) => ({ api: o.api, operationId: o.operationId, name: o.name })),
    helpers: ir.helpers.map((h) => h.name),
  };
}

/** The unions of the live stream messages, by direction. */
export function emitLiveUnions(ir: Ir): string {
  return (
    `\n/** A message the server sends on the live stream. Switch on \`type\`. */\nexport type StreamServerMessage = ${ir.liveServerMessages.map((m) => m.model).join(' | ')};\n` +
    `\n/** A text message the client sends on the live stream. */\nexport type StreamClientMessage = ${ir.liveClientMessages.map((m) => m.model).join(' | ')};\n`
  );
}
