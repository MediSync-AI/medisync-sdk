// Emits python/src/medisync/_generated: pydantic models of each spec, the operation table and
// the sync and async resource classes of the client.
import type { Api, Ir, Model, ObjectModel, Operation, TypeRef } from './ir.ts';
import { buildTree, walk, type Node } from './tree.ts';

const HEADER = (source: string) =>
  `# Generated by generator/src/main.ts from ${source}. Do not edit; run \`bun run generate\`.\n# pyright: reportUnusedImport=false\n`;
const MODULE: Record<Api, string> = { platform: 'platform_types', connect: 'connect_types', live: 'live_types' };
const ALIAS: Record<Api, string> = { platform: 'P', connect: 'C', live: 'L' };

const KEYWORDS = new Set(
  'False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield'.split(' '),
);
// Names a pydantic model field may not take: attributes of BaseModel.
const MODEL_RESERVED = new Set(['schema', 'json', 'dict', 'copy', 'construct', 'validate', 'fields', 'parse_obj', 'parse_raw', 'parse_file', 'from_orm', 'update_forward_refs', 'schema_json', 'model_config', 'model_fields', 'model_extra']);
// Keyword arguments every method takes; a body or query field may not have these names.
const METHOD_RESERVED = new Set(['self', 'idempotency_key', 'extra_headers', 'extra_query', 'extra_body', 'timeout']);

export const snake = (s: string) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .toLowerCase();

/** A Python identifier for a field name of the API. */
export function pyName(name: string, reserved: Set<string> = new Set()): string {
  let id = /^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : snake(name).replace(/^(\d)/, '_$1');
  if (KEYWORDS.has(id) || reserved.has(id)) id += '_';
  return id;
}

function docstring(text: string | undefined, indent: string): string {
  if (!text) return '';
  const body = text.trim().replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"');
  const lines = body.split('\n');
  if (lines.length === 1 && body.length < 90) return `${indent}"""${body}"""\n`;
  return `${indent}"""${lines.map((l, i) => (i === 0 ? l : l ? indent + l : '')).join('\n')}\n${indent}"""\n`;
}

/** The Python type of a TypeRef. `qualify` prefixes model names with their module alias. */
export function pyType(t: TypeRef, qualify = false, binary = 'FileTypes'): string {
  switch (t.kind) {
    case 'ref':
      return qualify ? `${ALIAS[t.api]}.${t.name}` : t.name;
    case 'string':
      return t.enum ? `Union[Literal[${t.enum.map((e) => JSON.stringify(e)).join(', ')}], str]` : 'str';
    case 'literal':
      return `Literal[${typeof t.value === 'boolean' ? (t.value ? 'True' : 'False') : JSON.stringify(t.value)}]`;
    case 'number':
      return 'float';
    case 'integer':
      return 'int';
    case 'boolean':
      return 'bool';
    case 'null':
      return 'None';
    case 'unknown':
      return 'Any';
    case 'binary':
      return binary;
    case 'array':
      return `List[${pyType(t.items, qualify, binary)}]`;
    case 'map':
      return `Dict[str, ${pyType(t.values, qualify, binary)}]`;
    case 'union': {
      const nonNull = t.of.filter((u) => u.kind !== 'null');
      const inner = nonNull.length === 1 ? pyType(nonNull[0] as TypeRef, qualify, binary) : `Union[${nonNull.map((u) => pyType(u, qualify, binary)).join(', ')}]`;
      return nonNull.length < t.of.length ? `Optional[${inner}]` : inner;
    }
  }
}

/** The type of a request argument: an object model also takes a plain dict. */
function paramType(t: TypeRef, models: Map<string, Model>): string {
  switch (t.kind) {
    case 'ref': {
      const m = models.get(t.name);
      if (m?.kind === 'object') return `Union[${ALIAS[t.api]}.${t.name}, Mapping[str, Any]]`;
      return pyType(t, true);
    }
    case 'array':
      return `Sequence[${paramType(t.items, models)}]`;
    case 'map':
      return `Mapping[str, ${paramType(t.values, models)}]`;
    case 'union': {
      const nonNull = t.of.filter((u) => u.kind !== 'null');
      const inner = nonNull.length === 1 ? paramType(nonNull[0] as TypeRef, models) : `Union[${nonNull.map((u) => paramType(u, models)).join(', ')}]`;
      return nonNull.length < t.of.length ? `Optional[${inner}]` : inner;
    }
    default:
      return pyType(t, true);
  }
}

function refsOf(t: TypeRef, out: Set<string>): void {
  if (t.kind === 'ref') out.add(t.name);
  else if (t.kind === 'array') refsOf(t.items, out);
  else if (t.kind === 'map') refsOf(t.values, out);
  else if (t.kind === 'union') for (const u of t.of) refsOf(u, out);
}

export function emitModels(models: Map<string, Model>, source: string, extra = ''): string {
  let out = HEADER(source);
  out += 'from __future__ import annotations\n\n';
  out += 'from typing import Any, Dict, List, Optional, Union\n\n';
  out += 'from pydantic import Field\n';
  out += 'from typing_extensions import Literal\n\n';
  out += 'from .._models import BaseModel\n';
  const all = [...models.values()];
  const exported = [...all.map((m) => m.name), ...[...extra.matchAll(/^([A-Za-z]+) = /gm)].map((m) => m[1] as string)];
  out += '\n__all__ = [\n' + exported.map((n) => `    ${JSON.stringify(n)},\n`).join('') + ']\n';
  const objects = all.filter((m): m is ObjectModel => m.kind === 'object');
  for (const m of objects) {
    out += `\n\nclass ${m.name}(BaseModel):\n`;
    out += docstring(m.description, '    ');
    if (!m.props.length) out += '    pass\n';
    for (const p of m.props) {
      const id = pyName(p.name, MODEL_RESERVED);
      let type = pyType(p.type, false, 'Any');
      const nullable = type.startsWith('Optional[') || type === 'Any';
      if (!p.required && !nullable) type = `Optional[${type}]`;
      const args: string[] = [];
      if (!p.required) args.push('default=None');
      if (id !== p.name) args.push(`alias=${JSON.stringify(p.name)}`);
      const value = args.length === 0 ? '' : args.length === 1 && args[0] === 'default=None' ? ' = None' : ` = Field(${args.join(', ')})`;
      out += `    ${id}: ${type}${value}\n`;
      if (p.description) out += docstring(p.description, '    ');
    }
  }
  // Aliases after the classes they name, in an order where each alias follows the aliases it uses.
  const aliases = all.filter((m) => m.kind === 'alias');
  const done = new Set<string>();
  const ordered: Model[] = [];
  const visit = (m: Model) => {
    if (done.has(m.name)) return;
    done.add(m.name);
    if (m.kind === 'alias') {
      const refs = new Set<string>();
      refsOf(m.type, refs);
      for (const r of refs) {
        const dep = models.get(r);
        if (dep?.kind === 'alias') visit(dep);
      }
    }
    ordered.push(m);
  };
  for (const a of aliases) visit(a);
  if (ordered.length) out += '\n';
  for (const a of ordered) {
    if (a.kind !== 'alias') continue;
    out += `\n${a.name} = ${pyType(a.type)}\n`;
    out += docstring(a.description, '');
  }
  out += extra;
  out += '\n';
  for (const m of objects) out += `${m.name}.model_rebuild()\n`;
  return out;
}

function opDoc(op: Operation): string {
  const parts = [op.summary, op.description && op.description !== op.summary ? op.description : undefined].filter(Boolean) as string[];
  const facts = [`\`${op.httpMethod} ${op.path}\``];
  if (op.x.scope) facts.push(`scope \`${op.x.scope}\``);
  if (op.x.verb) facts.push(`verb \`${op.x.verb}\``);
  if (op.x.phi) facts.push('answers hold patient data');
  if (op.x.metered) facts.push(`metered as \`${op.x.metered}\``);
  if (op.idempotency === 'required') facts.push('Idempotency-Key required (the SDK makes one)');
  parts.push(facts.join(', ') + '.');
  return parts.join('\n\n');
}

export function emitOperations(ir: Ir): string {
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += 'from typing import Dict\n\nfrom .._operation import OperationMeta\n\n';
  out += `API_VERSION = ${JSON.stringify(ir.version)}\n"""The API version of the specs this SDK was generated from."""\n\n`;
  out += 'OPERATIONS: Dict[str, OperationMeta] = {\n';
  for (const op of ir.operations) {
    out += `    ${JSON.stringify(op.name)}: OperationMeta(\n`;
    out += `        api=${JSON.stringify(op.api)},\n        operation_id=${JSON.stringify(op.operationId)},\n        method=${JSON.stringify(op.httpMethod)},\n        path=${JSON.stringify(op.path)},\n`;
    out += `        body=${op.body ? JSON.stringify(op.body.encoding) : 'None'},\n        query=${op.queryModel ? 'True' : 'False'},\n        response=${JSON.stringify(op.response.kind)},\n        idempotency=${JSON.stringify(op.idempotency)},\n        paginated=${op.page ? 'True' : 'False'},\n`;
    const comma = op.query.filter((q) => q.comma).map((q) => q.name);
    if (comma.length) out += `        comma_query=${JSON.stringify(comma).replace('[', '(').replace(']', ',)')},\n`;
    for (const [k, v] of Object.entries(op.x)) out += `        ${snake(k)}=${typeof v === 'boolean' ? (v ? 'True' : 'False') : JSON.stringify(v)},\n`;
    out += '    ),\n';
  }
  out += '}\n\n';
  out += `HELPERS = (\n${ir.helpers.map((h) => `    ${JSON.stringify(h.name)},\n`).join('')})\n"""Helpers on the client that are no API operation."""\n`;
  return out;
}

const methodName = (name: string) => snake(name);

interface Ctx {
  ir: Ir;
  isAsync: boolean;
}

function castType(op: Operation): string {
  switch (op.response.kind) {
    case 'empty':
      return 'None';
    case 'binary':
      return 'bytes';
    case 'text':
      return 'str';
    case 'json':
      return op.response.type && op.response.type.kind !== 'unknown' ? pyType(op.response.type, true) : 'Dict[str, Any]';
  }
}

function method(op: Operation, name: string, ctx: Ctx): string {
  const models = ctx.ir.models[op.api];
  const args: string[] = ['self'];
  const pathArgs: string[] = [];
  for (const p of op.pathParams) {
    const id = pyName(p.name);
    args.push(`${id}: ${pyType(p.type, true)}`);
    pathArgs.push(`${JSON.stringify(p.name)}: ${id}`);
  }
  args.push('*');
  const fields: { wire: string; id: string }[] = [];
  const addFields = (model: ObjectModel) => {
    for (const p of model.props) {
      const id = pyName(p.name, METHOD_RESERVED);
      if (op.pathParams.some((pp) => pyName(pp.name) === id)) throw new Error(`${op.operationId}: the field ${p.name} has the name of a path parameter`);
      let type = paramType(p.type, models);
      if (p.required) args.push(`${id}: ${type}`);
      else args.push(`${id}: Union[${type}, NotGiven] = NOT_GIVEN`);
      fields.push({ wire: p.name, id });
    }
  };
  // Required arguments first, then optional ones.
  const bodyModel = op.body ? (models.get(op.body.model) as ObjectModel) : undefined;
  const queryModel = op.queryModel ? (models.get(op.queryModel) as ObjectModel) : undefined;
  const fieldModel = bodyModel ?? queryModel;
  if (fieldModel) {
    const sorted: ObjectModel = { ...fieldModel, props: [...fieldModel.props.filter((p) => p.required), ...fieldModel.props.filter((p) => !p.required)] };
    addFields(sorted);
  }
  if (op.idempotency !== 'none') args.push('idempotency_key: Optional[str] = None');
  args.push('extra_headers: Optional[Mapping[str, str]] = None');
  args.push('extra_query: Optional[Mapping[str, object]] = None');
  if (op.body) args.push('extra_body: Optional[Mapping[str, object]] = None');
  args.push('timeout: Optional[float] = None');

  const fieldDict = fields.length ? `{${fields.map((f) => `${JSON.stringify(f.wire)}: ${f.id}`).join(', ')}}` : '{}';
  const call: string[] = [`OPERATIONS[${JSON.stringify(op.name)}]`];
  if (pathArgs.length) call.push(`path={${pathArgs.join(', ')}}`);
  if (op.body) call.push(`body=${fieldDict}`);
  if (op.queryModel) call.push(`query=${fieldDict}`);
  const opts = ['extra_headers=extra_headers', 'extra_query=extra_query', 'timeout=timeout'];
  if (op.idempotency !== 'none') opts.unshift('idempotency_key=idempotency_key');
  if (op.body) opts.push('extra_body=extra_body');
  call.push(`options=RequestOptions(${opts.join(', ')})`);

  const ind = '        ';
  let out = '';
  if (op.page) {
    const item = pyType(op.page.item, true);
    const raw = castType(op);
    const ret = ctx.isAsync ? `AsyncPaginator[${item}]` : `SyncCursorPage[${item}]`;
    out += `    def ${name}(\n${args.map((a) => `${ind}${a},\n`).join('')}    ) -> ${ret}:\n`;
    out += docstring(opDoc(op), ind);
    out += `${ind}return self._client._request_page(\n${call.map((c) => `${ind}    ${c},\n`).join('')}${ind}    item_type=${item},\n${ind}    list_type=${raw},\n${ind})\n`;
  } else {
    const ret = castType(op);
    out += `    ${ctx.isAsync ? 'async ' : ''}def ${name}(\n${args.map((a) => `${ind}${a},\n`).join('')}    ) -> ${ret}:\n`;
    out += docstring(opDoc(op), ind);
    out += `${ind}return cast(\n${ind}    ${ret},\n${ind}    ${ctx.isAsync ? 'await ' : ''}self._client._request(\n${call.map((c) => `${ind}        ${c},\n`).join('')}${ind}        cast_to=${ret},\n${ind}    ),\n${ind})\n`;
  }
  return out;
}

