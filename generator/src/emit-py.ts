function nodeClass(node: Node, isRoot: boolean, ctx: Ctx): string {
  const pre = ctx.isAsync ? 'Async' : '';
  const name = isRoot ? `${pre}MediSyncResources` : `${pre}${node.className}`;
  let out = isRoot
    ? `class ${name}(${ctx.isAsync ? 'AsyncCore' : 'SyncCore'}):\n    """The resources of the ${ctx.isAsync ? 'async ' : ''}MediSync client. Use \`${ctx.isAsync ? 'AsyncMediSync' : 'MediSync'}\`."""\n\n`
    : `class ${name}(${ctx.isAsync ? 'AsyncAPIResource' : 'SyncAPIResource'}):\n`;
  for (const [key, child] of node.children) out += `    ${pyName(snake(key))}: ${pre}${child.className}\n`;
  if (node.children.size) {
    out += '\n';
    if (isRoot) {
      out += '    def _init_resources(self) -> None:\n';
      for (const [key, child] of node.children) out += `        self.${pyName(snake(key))} = ${pre}${child.className}(self)\n`;
    } else {
      out += `    def __init__(self, client: ${ctx.isAsync ? 'AsyncCore' : 'SyncCore'}) -> None:\n        super().__init__(client)\n`;
      for (const [key, child] of node.children) out += `        self.${pyName(snake(key))} = ${pre}${child.className}(client)\n`;
    }
  }
  for (const m of node.methods) {
    out += '\n';
    if (m.helper) {
      const h = HELPER_PY[m.helper.name];
      if (!h) throw new Error(`No Python helper for ${m.helper.name}`);
      out += (ctx.isAsync ? h.async : h.sync).replace('__DOC__', docstring(m.helper.doc, '').trim());
    } else if (m.op?.custom) {
      const c = CUSTOM_PY[m.op.name];
      if (!c) throw new Error(`No Python code for the custom operation ${m.op.name}`);
      out += (ctx.isAsync ? c.async : c.sync).replace('__DOC__', docstring(opDoc(m.op), '        ').trim());
    } else if (m.op) {
      out += method(m.op, methodName(m.name), ctx);
    }
  }
  if (!node.children.size && !node.methods.length) out += '    pass\n';
  return out;
}

export function emitResources(ir: Ir): string {
  const tree = buildTree(ir);
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += `from __future__ import annotations

import asyncio
import threading
from typing import Any, AsyncIterator, Callable, Dict, Iterator, List, Mapping, Optional, Sequence, Union, cast

from typing_extensions import Literal

from . import connect_types as C
from . import platform_types as P
from .._core import AsyncAPIResource, AsyncCore, SyncAPIResource, SyncCore
from .._files import FileTypes
from .._helpers.capabilities import AsyncCapabilities, Capabilities
from .._helpers.follow import async_poll_events, async_wait_for_transfer, poll_events, wait_for_transfer
from .._helpers.transcriptions import async_wait_for_transcription, wait_for_transcription
from .._live import AsyncLiveStream, LiveStream
from .._operation import RequestOptions
from .._pagination import AsyncCursorPage, AsyncPaginator, SyncCursorPage
from .._types import NOT_GIVEN, NotGiven
from .operations import OPERATIONS

__all__ = ["MediSyncResources", "AsyncMediSyncResources"]
`;
  for (const isAsync of [false, true]) {
    const ctx: Ctx = { ir, isAsync };
    walk(tree, (node) => {
      if (node !== tree) out += `\n\n${nodeClass(node, false, ctx)}`;
    });
    out += `\n\n${nodeClass(tree, true, ctx)}`;
  }
  return out;
}

/** The snake_case names of the client methods, in the order of the operations. */
export function pythonNames(ir: Ir): Record<string, string> {
  const out: Record<string, string> = {};
  for (const op of ir.operations) out[op.name] = op.name.split('.').map(snake).join('.');
  for (const h of ir.helpers) out[h.name] = h.name.split('.').map(snake).join('.');
  return out;
}

