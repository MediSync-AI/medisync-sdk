// Emits the generated part of java/: a model class per schema, the operation table and the
// resource classes of the sync and the async client. Java wants one public class per file, so
// this emitter returns many files. The sync classes call their async twin and wait for it.
import type { Api, Ir, Model, ObjectModel, Operation, TypeRef } from './ir.ts';
import { camel, pascal } from './ir.ts';
import { opDoc } from './emit-ts.ts';
import { buildTree, walk, type Node } from './tree.ts';

export const JAVA_DIR = 'java/src/main/java/me/medisync';
const HEADER = (source: string) => `// Generated by generator/src/main.ts from ${source}. Do not edit; run \`bun run generate\`.\n`;
const PKG: Record<Api, string> = { platform: 'me.medisync.models', connect: 'me.medisync.models.connect', live: 'me.medisync.models' };
const DIR: Record<Api, string> = { platform: 'models', connect: 'models/connect', live: 'models' };

const KEYWORDS = new Set(
  'abstract assert boolean break byte case catch char class const continue default do double else enum extends final finally float for goto if implements import instanceof int interface long native new package private protected public return short static strictfp super switch synchronized this throw throws transient try void volatile while true false null var record yield'.split(' '),
);
/** Names the generated code uses from java.lang and java.util: no model may take them. */
const TAKEN = new Set(['String', 'Object', 'Long', 'Double', 'Boolean', 'Integer', 'Override', 'Deprecated', 'Class', 'Void', 'List', 'Map', 'Iterable', 'JsonModel', 'StreamEvent', 'FileInput', 'Page']);

/** Methods of Object and JsonModel: a fluent setter may not take their name. */
const OBJECT_METHODS = new Set(['equals', 'hashCode', 'toString', 'getClass', 'notify', 'notifyAll', 'wait', 'clone', 'finalize', 'toJson']);

/** java.lang names: a model with one of them gets a prefix, so a wildcard import does not hide them. */
const JAVA_LANG = new Set('Appendable Boolean Byte Character Class ClassLoader Comparable Compiler Deprecated Double Enum Error Exception Float Integer Iterable Long Math Module Number Object Override Package Process Record Runnable Runtime SafeVarargs Short StackWalker StrictMath String StringBuffer StringBuilder System Thread ThreadGroup ThreadLocal Throwable Void'.split(' '));

/** The Java class name of a model: `System` of Connect is `ConnectSystem`. */
export function javaClass(api: Api, name: string): string {
  return JAVA_LANG.has(name) ? `${api === 'connect' ? 'Connect' : 'MediSync'}${name}` : name;
}

/** A Java identifier for a field or parameter. */
export function javaId(name: string): string {
  const id = camel(name);
  return KEYWORDS.has(id) ? `${id}_` : id;
}

/** The accessor suffix of a property: `getPractitionerLink`. */
function accessor(name: string): string {
  const p = pascal(name);
  return p === 'Class' || p === 'AdditionalProperties' ? `${p}Value` : p;
}

/** Javadoc text: HTML escaped, backticks as <code>. */
export function javadoc(text: string | undefined, indent = ''): string {
  if (!text) return '';
  const body = text
    .trim()
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/@/g, '&#64;')
    .replace(/\*\//g, '*&#47;')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\n\n+/g, '\n<p>\n');
  const lines = body.split('\n');
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l ? ` ${l}` : ''}`).join('\n')}\n${indent} */\n`;
}

interface Ctx {
  ir: Ir;
  /** Fully qualified names this file imports. */
  imports: Set<string>;
  /** The package of the file: models of it need no import. */
  pkg: string;
}

function lookup(ir: Ir, t: Extract<TypeRef, { kind: 'ref' }>): Model {
  const m = ir.models[t.api].get(t.name);
  if (!m) throw new Error(`No model ${t.api}.${t.name}`);
  return m;
}

/** True when the value may be null on the wire. */
function nullable(t: TypeRef, ir: Ir): boolean {
  if (t.kind === 'null') return true;
  if (t.kind === 'union') return t.of.some((u) => nullable(u, ir));
  if (t.kind === 'ref') {
    const m = lookup(ir, t);
    return m.kind === 'alias' && nullable(m.type, ir);
  }
  return false;
}

/** The type without aliases and without null. */
function plain(t: TypeRef, ir: Ir): TypeRef {
  if (t.kind === 'ref') {
    const m = lookup(ir, t);
    return m.kind === 'alias' ? plain(m.type, ir) : t;
  }
  if (t.kind === 'union') {
    const of = t.of.filter((u) => u.kind !== 'null').map((u) => plain(u, ir));
    if (of.length === 1) return of[0] as TypeRef;
    return { kind: 'union', of };
  }
  return t;
}

/** The Java type of a TypeRef, boxed. */
export function javaType(t: TypeRef, ctx: Ctx): string {
  const p = plain(t, ctx.ir);
  switch (p.kind) {
    case 'ref': {
      const pkg = PKG[p.api];
      const cls = javaClass(p.api, p.name);
      if (pkg !== ctx.pkg) ctx.imports.add(`${pkg}.${cls}`);
      return cls;
    }
    case 'string':
      return 'String';
    case 'literal':
      return typeof p.value === 'string' ? 'String' : typeof p.value === 'boolean' ? 'Boolean' : Number.isInteger(p.value) ? 'Long' : 'Double';
    case 'number':
      return 'Double';
    case 'integer':
      return 'Long';
    case 'boolean':
      return 'Boolean';
    case 'binary':
      ctx.imports.add('me.medisync.FileInput');
      return 'FileInput';
    case 'array':
      ctx.imports.add('java.util.List');
      return `List<${javaType(p.items, ctx)}>`;
    case 'map':
      ctx.imports.add('java.util.Map');
      return `Map<String, ${javaType(p.values, ctx)}>`;
    case 'union':
      if (p.of.every((u) => u.kind === 'string' || (u.kind === 'literal' && typeof u.value === 'string'))) return 'String';
      if (p.of.every((u) => u.kind === 'number' || u.kind === 'integer')) return 'Double';
      return 'Object';
    default:
      return 'Object';
  }
}

/** Code for the Jackson JavaType of a TypeRef: `Types.of(Site.class)`. */
function typeExpr(t: TypeRef, ctx: Ctx): string {
  const p = plain(t, ctx.ir);
  if (p.kind === 'array') return `Types.listOf(${typeExpr(p.items, ctx)})`;
  if (p.kind === 'map') return `Types.mapOf(${typeExpr(p.values, ctx)})`;
  return `Types.of(${javaType(p, ctx)}.class)`;
}

function unionDoc(t: TypeRef, ir: Ir): string | undefined {
  const p = plain(t, ir);
  if (p.kind !== 'union') return undefined;
  const names = p.of.map((u) => (u.kind === 'ref' ? u.name : u.kind === 'array' ? 'a list' : u.kind === 'map' ? 'a map' : u.kind));
  return `One of: ${names.join(', ')}.`;
}

function imports(ctx: Ctx, extra: string[] = []): string {
  const all = [...new Set([...ctx.imports, ...extra])].filter((i) => i.slice(0, i.lastIndexOf('.')) !== ctx.pkg).sort();
  return all.map((i) => `import ${i};\n`).join('');
}

function literalValue(v: string | number | boolean): string {
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'boolean') return String(v);
  return Number.isInteger(v) ? `${v}L` : `${v}`;
}

function emitModel(m: ObjectModel, ir: Ir, source: string, liveServer: Set<string>): string {
  const ctx: Ctx = { ir, imports: new Set(['com.fasterxml.jackson.annotation.JsonProperty', 'me.medisync.core.JsonModel', 'org.jspecify.annotations.Nullable']), pkg: PKG[m.api] };
  let body = '';
  const fields: string[] = [];
  for (const p of m.props) {
    const type = javaType(p.type, ctx);
    const id = javaId(p.name);
    const lit = p.type.kind === 'literal' ? ` = ${literalValue(p.type.value)}` : '';
    fields.push(`  @JsonProperty(${JSON.stringify(p.name)})\n  private @Nullable ${type} ${id}${lit};\n`);
    const isNullable = nullable(p.type, ir);
    const optional = !p.required || isNullable;
    const ann = optional ? '@Nullable ' : '';
    const acc = accessor(p.name);
    const doc = [p.description, unionDoc(p.type, ir), p.deprecated ? '@deprecated The API keeps it for older clients.' : undefined].filter(Boolean).join('\n\n');
    const dep = p.deprecated ? '  @Deprecated\n' : '';
    const docText = doc ? javadoc(doc.replace('@deprecated', 'DEPRECATED_TAG'), '  ').replace('DEPRECATED_TAG', '@deprecated') : '';
    body += `\n${docText || `  /** The <code>${p.name}</code> field. */\n`}${dep}  public ${ann}${type} get${acc}() {\n    return ${id};\n  }\n`;
    body += `\n  /** Sets <code>${p.name}</code>.${isNullable ? ' Null sends an explicit null.' : ''} */\n${dep}  public void set${acc}(${ann}${type} value) {\n    this.${id} = value;\n${isNullable ? `    explicitNull(${JSON.stringify(p.name)}, value == null);\n` : ''}  }\n`;
    const fluent = OBJECT_METHODS.has(id) ? `${id}Value` : id;
    body += `\n  /** Sets <code>${p.name}</code> and returns this object. */\n${dep}  public ${javaClass(m.api, m.name)} ${fluent}(${ann}${type} value) {\n    set${acc}(value);\n    return this;\n  }\n`;
  }
  const iface = liveServer.has(m.name) ? ' implements StreamEvent' : '';
  const cls = javaClass(m.api, m.name);
  if (iface) ctx.imports.add('me.medisync.audio.StreamEvent');
  let out = HEADER(source);
  out += `package ${ctx.pkg};\n\n`;
  out += imports(ctx);
  out += '\n';
  out += javadoc(m.description) || `/** The <code>${m.name}</code> object of the API. */\n`;
  out += `public final class ${cls} extends JsonModel${iface} {\n`;
  out += fields.join('\n');
  out += `\n  /** An empty object. */\n  public ${cls}() {}\n`;
  out += body;
  out += '}\n';
  return out;
}

/** A class of constants for a string enum of the spec: `Role.DOCTOR`. The API may send other values. */
function emitEnum(name: string, api: Api, values: string[], description: string | undefined, source: string): string {
  const consts = values.map((v) => {
    let id = v.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_|_$/g, '');
    if (/^\d/.test(id)) id = `V_${id}`;
    return { id, v };
  });
  let out = HEADER(source);
  out += `package ${PKG[api]};\n\n`;
  out += javadoc(`${description ? `${description}\n\n` : ''}The known values of \`${name}\`. The API may add values; the models hold them as strings.`);
  out += `public final class ${name} {\n  private ${name}() {}\n`;
  for (const c of consts) out += `\n  /** <code>${c.v}</code> */\n  public static final String ${c.id} = ${JSON.stringify(c.v)};\n`;
  out += '}\n';
  return out;
}

function packageInfo(pkg: string, doc: string): string {
  return `${HEADER('specs/')}${javadoc(doc)}@NullMarked\npackage ${pkg};\n\nimport org.jspecify.annotations.NullMarked;\n`;
}

const constName = (dotted: string) => dotted.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/\./g, '_').toUpperCase();

function emitOperations(ir: Ir): string {
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += 'package me.medisync.resources;\n\nimport java.util.Arrays;\nimport java.util.Collections;\nimport java.util.LinkedHashMap;\nimport java.util.List;\nimport java.util.Map;\nimport me.medisync.core.OperationMeta;\n\n';
  out += '/** The API operations: what the client needs to know about each one. */\npublic final class Operations {\n  private Operations() {}\n\n';
  out += `  /** The API version of the specs this SDK was generated from. */\n  public static final String API_VERSION = ${JSON.stringify(ir.version)};\n`;
  for (const op of ir.operations) {
    const chain = [`OperationMeta.builder(${JSON.stringify(op.name)}, ${JSON.stringify(op.api)}, ${JSON.stringify(op.operationId)}, ${JSON.stringify(op.httpMethod)}, ${JSON.stringify(op.path)})`];
    if (op.body) chain.push(`.body(${JSON.stringify(op.body.encoding)})`);
    if (op.queryModel) chain.push('.query(true)');
    chain.push(`.response(${JSON.stringify(op.response.kind)})`);
    if (op.idempotency !== 'none') chain.push(`.idempotency(${JSON.stringify(op.idempotency)})`);
    if (op.page) chain.push('.paginated(true)');
    const comma = op.query.filter((q) => q.comma).map((q) => JSON.stringify(q.name));
    if (comma.length) chain.push(`.commaQuery(${comma.join(', ')})`);
    for (const [k, v] of Object.entries(op.x)) chain.push(`.x(${JSON.stringify(k)}, ${JSON.stringify(String(v))})`);
    chain.push('.build()');
    out += `\n  /** <code>${op.httpMethod} ${op.path}</code> */\n  public static final OperationMeta ${constName(op.name)} =\n      ${chain.join('\n          ')};\n`;
  }
  out += '\n  /** Every operation by its dotted method name. */\n  public static final Map<String, OperationMeta> ALL;\n\n  static {\n    Map<String, OperationMeta> all = new LinkedHashMap<>();\n';
  for (const op of ir.operations) out += `    all.put(${JSON.stringify(op.name)}, ${constName(op.name)});\n`;
  out += '    ALL = Collections.unmodifiableMap(all);\n  }\n';
  out += `\n  /** Helpers on the client that are no API operation. */\n  public static final List<String> HELPERS =\n      Collections.unmodifiableList(Arrays.asList(${ir.helpers.map((h) => JSON.stringify(h.name)).join(', ')}));\n}\n`;
  return out;
}

function emitServerMessages(ir: Ir): string {
  let out = HEADER('specs/asyncapi.yaml');
  out += 'package me.medisync.models;\n\nimport java.util.HashMap;\nimport java.util.Map;\nimport me.medisync.audio.StreamEvent;\nimport org.jspecify.annotations.Nullable;\n\n';
  out += '/** The classes of the messages the server sends on the live stream, by <code>type</code>. */\npublic final class StreamServerMessages {\n  private StreamServerMessages() {}\n\n';
  out += '  private static final Map<String, Class<? extends StreamEvent>> BY_TYPE = new HashMap<>();\n\n  static {\n';
  for (const m of ir.liveServerMessages) if (!HAND_WRITTEN_LIVE.has(m.model)) out += `    BY_TYPE.put(${JSON.stringify(m.type)}, ${javaClass('live', m.model)}.class);\n`;
  out += '  }\n\n  /** The class of a message type, or null for a type this SDK version does not know. */\n  public static @Nullable Class<? extends StreamEvent> forType(String type) {\n    return BY_TYPE.get(type);\n  }\n}\n';
  return out;
}

