function returnType(op: Operation, ctx: Ctx): { type: string; expr: string } {
  switch (op.response.kind) {
    case 'empty':
      return { type: 'Void', expr: 'Types.of(Void.class)' };
    case 'binary':
      return { type: 'byte[]', expr: 'Types.of(byte[].class)' };
    case 'text':
      return { type: 'String', expr: 'Types.of(String.class)' };
    case 'json':
      if (!op.response.type || op.response.type.kind === 'unknown') {
        ctx.imports.add('java.util.Map');
        return { type: 'Map<String, Object>', expr: 'Types.mapOf(Types.of(Object.class))' };
      }
      return { type: javaType(op.response.type, ctx), expr: typeExpr(op.response.type, ctx) };
  }
}

interface Sig {
  /** Parameters before the options, `String siteId, SiteCreate body`. */
  params: string[];
  /** Their names, for the calls of the overloads. */
  names: string[];
  /** The last parameter (body or query) may be left out. */
  optionalLast: boolean;
}

function signature(op: Operation, ctx: Ctx): Sig {
  const params: string[] = [];
  const names: string[] = [];
  for (const p of op.pathParams) {
    params.push(`String ${javaId(p.name)}`);
    names.push(javaId(p.name));
  }
  let optionalLast = false;
  const pkg = PKG[op.api];
  const use = (model: string) => {
    const cls = javaClass(op.api, model);
    if (pkg !== ctx.pkg) ctx.imports.add(`${pkg}.${cls}`);
    return cls;
  };
  if (op.body) {
    optionalLast = !op.body.required;
    params.push(`${optionalLast ? '@Nullable ' : ''}${use(op.body.model)} body`);
    names.push('body');
  } else if (op.queryModel) {
    optionalLast = !op.query.some((q) => q.required);
    params.push(`${optionalLast ? '@Nullable ' : ''}${use(op.queryModel)} query`);
    names.push('query');
  }
  return { params, names, optionalLast };
}

function overloads(sig: Sig, ret: string, name: string, doc: string, call: (names: string[]) => string, isVoidSync: boolean): string {
  let out = '';
  const all = [...sig.params, 'RequestOptions options'];
  const head = (params: string[]) => `  public ${ret} ${name}(${params.join(', ')})`;
  const delegate = (args: string[]) => `${isVoidSync ? '' : 'return '}${name}(${args.join(', ')});`;
  if (sig.optionalLast) {
    const short = sig.params.slice(0, -1);
    out += `${doc}${head(short)} {\n    ${delegate([...sig.names.slice(0, -1), 'null', 'RequestOptions.none()'])}\n  }\n\n`;
  }
  out += `${doc}${head(sig.params)} {\n    ${delegate([...sig.names, 'RequestOptions.none()'])}\n  }\n\n`;
  out += `${doc}${head(all)} {\n    ${call([...sig.names, 'options'])}\n  }\n`;
  return out;
}

function asyncMethod(op: Operation, name: string, ctx: Ctx): string {
  const sig = signature(op, ctx);
  const doc = javadoc(opDoc(op), '  ');
  const args: string[] = ['RequestArgs.create()'];
  for (const p of op.pathParams) args.push(`.path(${JSON.stringify(p.name)}, ${javaId(p.name)})`);
  if (op.body) args.push('.body(body)');
  if (op.queryModel) args.push('.query(query)');
  const meta = `Operations.${constName(op.name)}`;
  if (op.page) {
    const item = javaType(op.page.item, ctx);
    const raw = returnType(op, ctx);
    ctx.imports.add('me.medisync.Page');
    const ret = `CompletableFuture<Page<${item}, ${raw.type}>>`;
    return overloads(sig, ret, name, doc, () => `return core.requestPage(${meta}, ${args.join('')}, ${typeExpr(op.page!.item, ctx)}, ${raw.expr}, options);`, false);
  }
  const r = returnType(op, ctx);
  return overloads(sig, `CompletableFuture<${r.type}>`, name, doc, () => `return core.request(${meta}, ${args.join('')}, ${r.expr}, options);`, false);
}

function syncMethod(op: Operation, name: string, ctx: Ctx): string {
  const sig = signature(op, ctx);
  const doc = javadoc(opDoc(op), '  ');
  let ret: string;
  if (op.page) {
    ctx.imports.add('me.medisync.Page');
    ret = `Page<${javaType(op.page.item, ctx)}, ${returnType(op, ctx).type}>`;
  } else {
    const r = returnType(op, ctx);
    ret = r.type === 'Void' ? 'void' : r.type;
  }
  const isVoid = ret === 'void';
  return overloads(sig, ret, name, doc, (names) => `${isVoid ? '' : 'return '}ClientCore.join(async.${name}(${names.join(', ')}));`, isVoid);
}

function nodeFile(node: Node, isRoot: boolean, isAsync: boolean, ir: Ir): [string, string] {
  const pkg = 'me.medisync.resources';
  const ctx: Ctx = { ir, imports: new Set(['me.medisync.RequestOptions', 'me.medisync.core.ClientCore']), pkg };
  const suffix = isAsync ? 'Async' : '';
  const name = isRoot ? (isAsync ? 'MediSyncAsyncResources' : 'MediSyncResources') : `${node.className}Service${suffix}`;
  let members = '';
  for (const m of node.methods) {
    members += '\n';
    const table = m.helper ? HELPER_JAVA[m.helper.name] : m.op?.custom ? CUSTOM_JAVA[m.op.name] : undefined;
    if (m.helper || m.op?.custom) {
      if (!table) throw new Error(`No Java code for ${m.helper?.name ?? m.op?.name}`);
      for (const i of table.imports) ctx.imports.add(i);
      ctx.imports.add('org.jspecify.annotations.Nullable');
      const doc = javadoc(m.helper ? m.helper.doc : opDoc(m.op as Operation), '  ');
      members += (isAsync ? table.async : table.sync).replace('__DOC__', doc.replace(/^ {2}/, ''));
      continue;
    }
    if (m.op) members += isAsync ? asyncMethod(m.op, m.name, ctx) : syncMethod(m.op, m.name, ctx);
  }
  if (members.includes('@Nullable')) ctx.imports.add('org.jspecify.annotations.Nullable');
  if (isAsync) {
    ctx.imports.add('java.util.concurrent.CompletableFuture');
    if (members.includes('RequestArgs.')) ctx.imports.add('me.medisync.core.RequestArgs');
    if (members.includes('Types.')) ctx.imports.add('me.medisync.core.Types');
  }
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += `package ${pkg};\n\n`;
  const used = (i: string) => {
    const simple = i.slice(i.lastIndexOf('.') + 1);
    return new RegExp(`\\b${simple.replace('$', '\\$')}\\b`).test(members) || (simple === 'ClientCore' && isAsync) || (simple === 'RequestOptions' && members.includes('RequestOptions'));
  };
  out += imports({ ...ctx, imports: new Set([...ctx.imports].filter(used)) });
  out += '\n';
  if (isRoot) {
    out += `/** The resources of the ${isAsync ? 'async ' : ''}MediSync client. Use <code>${isAsync ? 'MediSyncClient.async()' : 'MediSyncClient'}</code>. */\npublic abstract class ${name} {\n`;
  } else {
    out += `/** The <code>${node.path}</code> methods${isAsync ? ', async' : ''}. */\npublic final class ${name} {\n`;
  }
  if (isAsync && !isRoot) out += '  private final ClientCore core;\n';
  if (!isAsync && !isRoot && node.methods.length) out += `  private final ${node.className}ServiceAsync async;\n`;
  for (const [key, child] of node.children) out += `  private final ${child.className}Service${suffix} ${javaId(key)};\n`;
  const ctorVis = isRoot ? 'protected' : '';
  const ctorSig = isAsync ? 'ClientCore core' : isRoot ? 'MediSyncAsyncResources async' : `${node.className}ServiceAsync async`;
  out += `\n  ${ctorVis ? `${ctorVis} ` : ''}${name}(${ctorSig}) {\n`;
  if (isAsync && !isRoot) out += '    this.core = core;\n';
  if (!isAsync && !isRoot && node.methods.length) out += '    this.async = async;\n';
  for (const [key, child] of node.children) out += isAsync ? `    this.${javaId(key)} = new ${child.className}ServiceAsync(core);\n` : `    this.${javaId(key)} = new ${child.className}Service(async.${javaId(key)}());\n`;
  out += '  }\n';
  for (const [key, child] of node.children) out += `\n  /** The <code>${child.path}</code> methods. */\n  public ${child.className}Service${suffix} ${javaId(key)}() {\n    return ${javaId(key)};\n  }\n`;
  out += members;
  out += '}\n';
  return [`${JAVA_DIR}/resources/${name}.java`, out];
}

// Live messages this language keeps by hand: 0.2.0 published them in the audio package before the
// spec had them. One class per message, so the generator writes no second one and no registry entry.
const HAND_WRITTEN_LIVE = new Set(['StreamFlushed']);

export function emitJava(ir: Ir): Record<string, string> {
  const files: Record<string, string> = {};
  const sources: Record<Api, string> = { platform: 'specs/openapi.json', connect: 'specs/connect-openapi.json', live: 'specs/asyncapi.yaml' };
  const liveServer = new Set(ir.liveServerMessages.map((m) => m.model));
  const seen = new Map<string, Api>();
  for (const api of ['platform', 'connect', 'live'] as Api[]) {
    for (const m of ir.models[api].values()) {
      if (api === 'live' && HAND_WRITTEN_LIVE.has(m.name)) continue;
      if (TAKEN.has(m.name)) throw new Error(`The model ${m.name} has a name the Java code needs`);
      const key = `${PKG[api]}.${javaClass(api, m.name)}`;
      if (seen.has(key)) throw new Error(`Two Java classes ${key}`);
      seen.set(key, api);
      if (m.kind === 'object') files[`${JAVA_DIR}/${DIR[api]}/${javaClass(api, m.name)}.java`] = emitModel(m, ir, sources[api], liveServer);
      else if (m.type.kind === 'string' && m.type.enum) files[`${JAVA_DIR}/${DIR[api]}/${javaClass(api, m.name)}.java`] = emitEnum(javaClass(api, m.name), api, m.type.enum, m.description, sources[api]);
    }
  }
  files[`${JAVA_DIR}/models/package-info.java`] = packageInfo('me.medisync.models', 'The objects of the platform API and of the live stream.');
  files[`${JAVA_DIR}/models/connect/package-info.java`] = packageInfo('me.medisync.models.connect', 'The objects of MediSync Connect.');
  files[`${JAVA_DIR}/resources/package-info.java`] = packageInfo('me.medisync.resources', 'The methods of the client, by namespace. Generated from the specs.');
  files[`${JAVA_DIR}/resources/Operations.java`] = emitOperations(ir);
  files[`${JAVA_DIR}/models/StreamServerMessages.java`] = emitServerMessages(ir);
  const tree = buildTree(ir);
  const classNames = new Set<string>();
  walk(tree, (node) => {
    for (const isAsync of [false, true]) {
      const [path, code] = nodeFile(node, node === tree, isAsync, ir);
      if (classNames.has(path)) throw new Error(`Two resource classes ${path}`);
      classNames.add(path);
      files[path] = code;
    }
  });
  return files;
}

/** The method names of the Java client: the same dotted camelCase names as TypeScript. */
export function javaNames(ir: Ir): Record<string, string> {
  const out: Record<string, string> = {};
  for (const op of ir.operations) out[op.name] = op.name;
  for (const h of ir.helpers) out[h.name] = h.name;
  return out;
}
