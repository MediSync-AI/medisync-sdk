const CT = 'CancellationToken cancellationToken = default';

const HELPER_CS: Record<string, string> = {
  'audio.transcriptions.wait': `    public Task<P.Transcription> WaitAsync(string id, TranscriptionWaitOptions? options = null, ${CT})
        => Waits.TranscriptionAsync((i, ct) => GetAsync(i, null, ct), id, options ?? new TranscriptionWaitOptions(), _core.Sleep, cancellationToken);
`,
  'connect.transfers.wait': `    public Task<C.Transfer> WaitAsync(string transferId, TransferWaitOptions? options = null, ${CT})
        => Waits.TransferAsync((i, ct) => GetAsync(i, null, ct), transferId, options ?? new TransferWaitOptions(), _core.Sleep, cancellationToken);
`,
  'connect.events.poll': `    public IAsyncEnumerable<Page<C.Event, C.EventList>> PollAsync(C.EventsListQuery? query = null, PollOptions? options = null, ${CT})
        => Waits.PollEventsAsync(this, query, options ?? new PollOptions(), _core.Sleep, cancellationToken);
`,
  'connect.capabilities.forConnection': `    public Capabilities ForConnection(string connectionId)
        => new(connectionId, ct => GetAsync(connectionId, null, ct));
`,
};

const CUSTOM_CS: Record<string, string> = {
  'audio.stream.open': `    public Task<LiveStream> OpenAsync(StreamOptions? options = null, ${CT})
        => LiveStream.OpenAsync(_core, options ?? new StreamOptions(), cancellationToken);
`,
};

function returnType(op: Operation, ctx: Ctx): string {
  switch (op.response.kind) {
    case 'empty':
      return '';
    case 'binary':
      return 'byte[]';
    case 'text':
      return 'string';
    case 'json':
      return !op.response.type || op.response.type.kind === 'unknown' ? 'JsonElement' : csType(op.response.type, ctx);
  }
}

function method(op: Operation, name: string, ctx: Ctx): string {
  const params: string[] = [];
  const args: string[] = ['new RequestArgs()'];
  for (const p of op.pathParams) {
    params.push(`string ${csId(p.name)}`);
    args.push(`.Path(${JSON.stringify(p.name)}, ${csId(p.name)})`);
  }
  const alias = ALIAS[op.api];
  if (op.body) {
    const model = csClass(op.api, op.body.model);
    params.push(op.body.required ? `${alias}.${model} body` : `${alias}.${model}? body = null`);
    args.push('.WithBody(body)');
  } else if (op.queryModel) {
    const required = op.query.some((q) => q.required);
    const model = csClass(op.api, op.queryModel);
    params.push(required ? `${alias}.${model} query` : `${alias}.${model}? query = null`);
    args.push('.WithQuery(query)');
  }
  params.push('RequestOptions? options = null', CT);
  const meta = `Operations.${fieldName(op.name)}`;
  let out = xmldoc(opDoc(op), '    ');
  const a = args.join('');
  if (op.page) {
    const item = csType(op.page.item, ctx);
    const raw = returnType(op, ctx);
    out += `    public PageTask<${item}, ${raw}> ${name}(${params.join(', ')})\n        => _core.RequestPage<${item}, ${raw}>(${meta}, ${a}, options, cancellationToken);\n`;
    return out;
  }
  const rt = returnType(op, ctx);
  if (!rt) out += `    public Task ${name}(${params.join(', ')})\n        => _core.SendAsync(${meta}, ${a}, options, cancellationToken);\n`;
  else out += `    public Task<${rt}> ${name}(${params.join(', ')})\n        => _core.RequestAsync<${rt}>(${meta}, ${a}, options, cancellationToken);\n`;
  return out;
}

const methodName = (name: string, isAsync = true) => `${pascal(name)}${isAsync ? 'Async' : ''}`;

function nodeClass(node: Node, isRoot: boolean, ir: Ir): string {
  const ctx: Ctx = { ir, qualify: true };
  const name = isRoot ? 'MediSyncResources' : `${node.className}Service`;
  let out = '\n';
  out += isRoot
    ? `/// <summary>The resources of the MediSync client. Use <c>MediSyncClient</c>.</summary>\npublic abstract class ${name}\n{\n`
    : `/// <summary>The <c>${node.path}</c> methods.</summary>\npublic sealed class ${name}\n{\n`;
  if (!isRoot) out += '    private readonly ClientCore _core;\n\n';
  out += `    ${isRoot ? 'private protected' : 'internal'} ${name}(ClientCore core)\n    {\n`;
  if (!isRoot) out += '        _core = core;\n';
  for (const [key, child] of node.children) out += `        ${pascal(key)} = new ${child.className}Service(core);\n`;
  out += '    }\n';
  for (const [key, child] of node.children) out += `\n    /// <summary>The <c>${child.path}</c> methods.</summary>\n    public ${child.className}Service ${pascal(key)} { get; }\n`;
  for (const m of node.methods) {
    out += '\n';
    if (m.helper) {
      const code = HELPER_CS[m.helper.name];
      if (!code) throw new Error(`No C# helper for ${m.helper.name}`);
      out += xmldoc(m.helper.doc, '    ') + code;
    } else if (m.op?.custom) {
      const code = CUSTOM_CS[m.op.name];
      if (!code) throw new Error(`No C# code for ${m.op.name}`);
      out += xmldoc(opDoc(m.op), '    ') + code;
    } else if (m.op) {
      out += method(m.op, methodName(m.name), ctx);
    }
  }
  out += '}\n';
  return out;
}

function emitResources(ir: Ir): string {
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += `using System.Collections.Generic;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using MediSync.Core;
using P = MediSync.Models;
using C = MediSync.Models.Connect;

namespace MediSync.Resources;
`;
  const tree = buildTree(ir);
  walk(tree, (node) => {
    out += nodeClass(node, node === tree, ir);
  });
  return out;
}

// Live messages this language keeps by hand: 0.2.0 published them in the audio package before the
// spec had them. One class per message, so the generator writes no second one and no registry entry.
const HAND_WRITTEN_LIVE = new Set(['StreamFlushed']);

export function emitCs(ir: Ir): Record<string, string> {
  const liveServer = new Set(ir.liveServerMessages.map((m) => m.model));
  const names = new Set<string>();
  for (const api of ['platform', 'live'] as Api[]) for (const m of ir.models[api].values()) {
    if (names.has(m.name)) throw new Error(`Two C# types MediSync.Models.${m.name}`);
    names.add(m.name);
  }
  return {
    [`${CS_DIR}/Models.Platform.cs`]: emitModels(ir.models.platform, 'platform', ir, 'specs/openapi.json', liveServer),
    [`${CS_DIR}/Models.Connect.cs`]: emitModels(ir.models.connect, 'connect', ir, 'specs/connect-openapi.json', liveServer),
    [`${CS_DIR}/Models.Live.cs`]: emitModels(ir.models.live, 'live', ir, 'specs/asyncapi.yaml', liveServer) + serverMessages(ir),
    [`${CS_DIR}/Operations.cs`]: emitOperations(ir),
    [`${CS_DIR}/Resources.cs`]: emitResources(ir),
  };
}

/** The member names of the .NET client: `Connect.Transfers.CreateAsync`. */
export function dotnetNames(ir: Ir): Record<string, string> {
  const out: Record<string, string> = {};
  const dotted = (name: string, isAsync: boolean) => {
    const parts = name.split('.');
    const last = parts.pop() as string;
    return [...parts.map(pascal), methodName(last, isAsync)].join('.');
  };
  for (const op of ir.operations) out[op.name] = dotted(op.name, true);
  for (const h of ir.helpers) out[h.name] = dotted(h.name, h.name !== 'connect.capabilities.forConnection');
  return out;
}
