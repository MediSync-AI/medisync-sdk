// Emits dotnet/src/MediSync/Generated: the model classes of each spec, the operation table and
// the resource classes of the client. Every method is async and takes a CancellationToken.
import type { Api, Ir, Model, ObjectModel, Operation, TypeRef } from './ir.ts';
import { camel, pascal } from './ir.ts';
import { opDoc } from './emit-ts.ts';
import { buildTree, walk, type Node } from './tree.ts';

export const CS_DIR = 'dotnet/src/MediSync/Generated';
const HEADER = (source: string) => `// <auto-generated>\n// Generated by generator/src/main.ts from ${source}. Do not edit; run \`bun run generate\`.\n// </auto-generated>\n#nullable enable\n`;
const NS: Record<Api, string> = { platform: 'MediSync.Models', connect: 'MediSync.Models.Connect', live: 'MediSync.Models' };
const ALIAS: Record<Api, string> = { platform: 'P', connect: 'C', live: 'P' };

const KEYWORDS = new Set(
  'abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while'.split(' '),
);
/** Names the generated code uses: no model may take them. */
const TAKEN = new Set(['JsonModel', 'IStreamEvent', 'FileInput', 'Page', 'PageTask', 'Task', 'Operations', 'OperationMeta']);

/** Names of the System namespace: a model with one of them gets a prefix, so `using System;` does not make it ambiguous. */
const CS_SYSTEM = new Set('Action Activator AppContext AppDomain Array Attribute Boolean Buffer Byte Char Console Convert DateTime DateTimeOffset Decimal Delegate Double Enum Environment Exception Func GC Guid Index Int16 Int32 Int64 Lazy Math Nullable Object Random Range Single Span String TimeSpan Tuple Type Uri Version'.split(' '));

/** The C# class name of a model: `Environment` of Connect is `ConnectEnvironment`. */
export function csClass(api: Api, name: string): string {
  return CS_SYSTEM.has(name) ? `${api === 'connect' ? 'Connect' : 'MediSync'}${name}` : name;
}

const csId = (name: string) => {
  const id = camel(name);
  return KEYWORDS.has(id) ? `@${id}` : id;
};

/** XML doc text: escaped, backticks as <c>. */
export function xmldoc(text: string | undefined, indent = ''): string {
  if (!text) return '';
  const body = text
    .trim()
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/`([^`]+)`/g, '<c>$1</c>');
  const paras = body.split(/\n\n+/);
  const lines = paras.length === 1 ? (paras[0] as string).split('\n') : paras.flatMap((p, i) => [...(i ? ['<para>'] : []), ...p.split('\n'), ...(i ? ['</para>'] : [])]);
  return `${indent}/// <summary>\n${lines.map((l) => `${indent}/// ${l}`.trimEnd()).join('\n')}\n${indent}/// </summary>\n`;
}

interface Ctx {
  ir: Ir;
  /** Qualify model names with their namespace alias (resources), or not (model files). */
  qualify: boolean;
}

function lookup(ir: Ir, t: Extract<TypeRef, { kind: 'ref' }>): Model {
  const m = ir.models[t.api].get(t.name);
  if (!m) throw new Error(`No model ${t.api}.${t.name}`);
  return m;
}

function nullable(t: TypeRef, ir: Ir): boolean {
  if (t.kind === 'null') return true;
  if (t.kind === 'union') return t.of.some((u) => nullable(u, ir));
  if (t.kind === 'ref') {
    const m = lookup(ir, t);
    return m.kind === 'alias' && nullable(m.type, ir);
  }
  return false;
}

function plain(t: TypeRef, ir: Ir): TypeRef {
  if (t.kind === 'ref') {
    const m = lookup(ir, t);
    return m.kind === 'alias' ? plain(m.type, ir) : t;
  }
  if (t.kind === 'union') {
    const of = t.of.filter((u) => u.kind !== 'null').map((u) => plain(u, ir));
    if (of.length === 1) return of[0] as TypeRef;
    return { kind: 'union', of };
  }
  return t;
}

const VALUE_TYPES = new Set(['long', 'double', 'bool']);

/** The C# type of a TypeRef, without `?`. */
export function csType(t: TypeRef, ctx: Ctx): string {
  const p = plain(t, ctx.ir);
  switch (p.kind) {
    case 'ref':
      return ctx.qualify ? `${ALIAS[p.api]}.${csClass(p.api, p.name)}` : csClass(p.api, p.name);
    case 'string':
      return 'string';
    case 'literal':
      return typeof p.value === 'string' ? 'string' : typeof p.value === 'boolean' ? 'bool' : Number.isInteger(p.value) ? 'long' : 'double';
    case 'number':
      return 'double';
    case 'integer':
      return 'long';
    case 'boolean':
      return 'bool';
    case 'binary':
      return 'FileInput';
    case 'array': {
      const inner = csType(p.items, ctx);
      return `IList<${inner}${nullable(p.items, ctx.ir) && !inner.endsWith('?') ? '?' : ''}>`;
    }
    case 'map': {
      const inner = csType(p.values, ctx);
      return `IDictionary<string, ${inner}${nullable(p.values, ctx.ir) ? '?' : ''}>`;
    }
    case 'union':
      if (p.of.every((u) => u.kind === 'string' || (u.kind === 'literal' && typeof u.value === 'string'))) return 'string';
      if (p.of.every((u) => u.kind === 'number' || u.kind === 'integer')) return 'double';
      return 'object';
    default:
      return 'object';
  }
}

function unionDoc(t: TypeRef, ir: Ir): string | undefined {
  const p = plain(t, ir);
  if (p.kind !== 'union') return undefined;
  const names = p.of.map((u) => (u.kind === 'ref' ? u.name : u.kind === 'array' ? 'a list' : u.kind === 'map' ? 'a map' : u.kind));
  return `One of: ${names.join(', ')}. A value read from the API is a JsonElement.`;
}

function literal(v: string | number | boolean): string {
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'boolean') return String(v);
  return Number.isInteger(v) ? `${v}L` : `${v}`;
}

/** Members of object and JsonModel: a property may not take their name. */
const OBJECT_MEMBERS = new Set(['Equals', 'GetHashCode', 'ToString', 'GetType', 'ToJson', 'AdditionalProperties', 'ExplicitNull', 'MemberwiseClone', 'Finalize']);

function propName(name: string, className: string): string {
  let p = pascal(name);
  if (/^\d/.test(p)) p = `_${p}`;
  if (p === className || OBJECT_MEMBERS.has(p)) p = `${p}Value`;
  return p;
}

function emitModel(m: ObjectModel, ir: Ir, liveServer: Set<string>): string {
  const ctx: Ctx = { ir, qualify: false };
  const iface = liveServer.has(m.name) ? ', IStreamEvent' : '';
  let out = '\n';
  out += xmldoc(m.description, '') || `/// <summary>The <c>${m.name}</c> object of the API.</summary>\n`;
  out += `public sealed class ${csClass(m.api, m.name)} : JsonModel${iface}\n{\n`;
  const members: string[] = [];
  for (const p of m.props) {
    const base = csType(p.type, ctx);
    const isNullable = nullable(p.type, ir);
    const optional = !p.required || isNullable;
    const type = optional && base !== 'object' ? `${base}?` : base === 'object' ? 'object?' : base;
    const name = propName(p.name, csClass(m.api, m.name));
    const doc = [p.description, unionDoc(p.type, ir)].filter(Boolean).join('\n\n');
    let code = xmldoc(doc, '    ') || `    /// <summary>The <c>${p.name}</c> field.</summary>\n`;
    if (p.deprecated) code += '    [Obsolete("The API keeps it for older clients.")]\n';
    code += `    [JsonPropertyName(${JSON.stringify(p.name)})]\n`;
    if (isNullable) {
      const field = `_${camel(p.name)}`;
      code += `    public ${type} ${name}\n    {\n        get => ${field};\n        set\n        {\n            ${field} = value;\n            ExplicitNull(${JSON.stringify(p.name)}, value is null);\n        }\n    }\n\n    private ${type} ${field};\n`;
    } else {
      const init = p.type.kind === 'literal' ? ` = ${literal(p.type.value)};` : !optional && !VALUE_TYPES.has(base) ? ' = default!;' : '';
      code += `    public ${type} ${name} { get; set; }${init}\n`;
    }
    members.push(code);
  }
  out += members.join('\n');
  out += '}\n';
  return out;
}

function emitEnum(name: string, values: string[], description: string | undefined): string {
  let out = '\n';
  out += xmldoc(`${description ? `${description}\n\n` : ''}The known values of \`${name}\`. The API may add values; the models hold them as strings.`);
  out += `public static class ${name}\n{\n`;
  out += values
    .map((v) => {
      let id = pascal(v.replace(/[^A-Za-z0-9]+/g, '_'));
      if (/^\d/.test(id)) id = `V${id}`;
      if (id === name) id = `${id}Value`;
      return `    /// <summary><c>${v}</c></summary>\n    public const string ${id} = ${JSON.stringify(v)};\n`;
    })
    .join('\n');
  out += '}\n';
  return out;
}

function emitModels(models: Map<string, Model>, api: Api, ir: Ir, source: string, liveServer: Set<string>): string {
  let out = HEADER(source);
  out += 'using System;\nusing System.Collections.Generic;\nusing System.Text.Json.Serialization;\n\n';
  out += `namespace ${NS[api]};\n`;
  for (const m of models.values()) {
    if (TAKEN.has(m.name)) throw new Error(`The model ${m.name} has a name the C# code needs`);
    if (api === 'live' && HAND_WRITTEN_LIVE.has(m.name)) continue;
    if (m.kind === 'object') out += emitModel(m, ir, liveServer);
    else if (m.type.kind === 'string' && m.type.enum) out += emitEnum(csClass(api, m.name), m.type.enum, m.description);
  }
  return out;
}

function serverMessages(ir: Ir): string {
  let out = '\n/// <summary>The classes of the messages the server sends on the live stream, by <c>type</c>.</summary>\npublic static class StreamServerMessages\n{\n';
  out += '    private static readonly Dictionary<string, Type> ByType = new()\n    {\n';
  for (const m of ir.liveServerMessages) if (!HAND_WRITTEN_LIVE.has(m.model)) out += `        [${JSON.stringify(m.type)}] = typeof(${csClass('live', m.model)}),\n`;
  out += '    };\n\n    /// <summary>The class of a message type, or null for a type this SDK version does not know.</summary>\n    public static Type? ForType(string type) => ByType.TryGetValue(type, out var t) ? t : null;\n}\n';
  return out;
}

const fieldName = (dotted: string) => dotted.split('.').map(pascal).join('');

function emitOperations(ir: Ir): string {
  let out = HEADER('specs/openapi.json and specs/connect-openapi.json');
  out += 'using System.Collections.Generic;\nusing MediSync.Core;\n\nnamespace MediSync.Resources;\n\n';
  out += '/// <summary>The API operations: what the client needs to know about each one.</summary>\npublic static class Operations\n{\n';
  out += `    /// <summary>The API version of the specs this SDK was generated from.</summary>\n    public const string ApiVersion = ${JSON.stringify(ir.version)};\n`;
  for (const op of ir.operations) {
    const init: string[] = [];
    if (op.body) init.push(`Body = ${JSON.stringify(op.body.encoding)}`);
    if (op.queryModel) init.push('Query = true');
    init.push(`Response = ${JSON.stringify(op.response.kind)}`);
    if (op.idempotency !== 'none') init.push(`Idempotency = ${JSON.stringify(op.idempotency)}`);
    if (op.page) init.push('Paginated = true');
    const comma = op.query.filter((q) => q.comma).map((q) => JSON.stringify(q.name));
    if (comma.length) init.push(`CommaQuery = new[] { ${comma.join(', ')} }`);
    const x = Object.entries(op.x);
    if (x.length) init.push(`X = new Dictionary<string, string> { ${x.map(([k, v]) => `[${JSON.stringify(k)}] = ${JSON.stringify(String(v))}`).join(', ')} }`);
    out += `\n    /// <summary><c>${op.httpMethod} ${op.path}</c></summary>\n    public static readonly OperationMeta ${fieldName(op.name)} = new(${JSON.stringify(op.name)}, ${JSON.stringify(op.api)}, ${JSON.stringify(op.operationId)}, ${JSON.stringify(op.httpMethod)}, ${JSON.stringify(op.path)})\n    {\n${init.map((i) => `        ${i},\n`).join('')}    };\n`;
  }
  out += '\n    /// <summary>Every operation by its dotted method name.</summary>\n    public static readonly IReadOnlyDictionary<string, OperationMeta> All = new Dictionary<string, OperationMeta>\n    {\n';
  for (const op of ir.operations) out += `        [${JSON.stringify(op.name)}] = ${fieldName(op.name)},\n`;
  out += '    };\n';
  out += `\n    /// <summary>Helpers on the client that are no API operation.</summary>\n    public static readonly IReadOnlyList<string> Helpers = new[] { ${ir.helpers.map((h) => JSON.stringify(h.name)).join(', ')} };\n}\n`;
  return out;
}

